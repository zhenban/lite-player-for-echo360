// Packs the page (src/page/) and the font into src/assets.gen.js, so the Worker serves them
// itself, after the access check (Static Assets would be served before the Worker runs).
// Run by `npm test`, `npm run dev` and `npm run deploy`; the output is not committed.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const page = (f) => readFileSync(new URL('src/page/' + f, import.meta.url), 'utf8');
const font = readFileSync(new URL('node_modules/@fontsource-variable/instrument-sans/files/instrument-sans-latin-standard-normal.woff2', import.meta.url));
// The page's scripts, in order, as one script (each file is a plain script sharing one scope).
const js = '(() => {\n\'use strict\';\n' + ['i18n.js', 'format.js', 'charts.js', 'app.js'].map(page).join('\n') + '\n})();\n';
const assets = { html: page('index.html'), css: page('app.css'), js, font: font.toString('base64') };
// --bundle: also write the page script alone, for ESLint (the page files share one scope).
if (process.argv.includes('--bundle')) {
  mkdirSync(new URL('dev/out/', import.meta.url), { recursive: true });
  writeFileSync(new URL('dev/out/page.bundle.js', import.meta.url), js);
}
writeFileSync(new URL('src/assets.gen.js', import.meta.url),
  '// Generated by build-assets.mjs from src/page/ and the font. Do not edit.\nexport const ASSETS = ' + JSON.stringify(assets) + ';\n');
